export function OpenDataIcon({
  name,
  className,
  size = 20,
}: {
  name?: string;
  className?: string;
  size?: number;
}) {
  const normalized = (name ?? "").toLowerCase().trim();
  const Icon = icons[normalized] ?? Database;
  return <Icon className={className} size={size} aria-hidden="true" />;
}
